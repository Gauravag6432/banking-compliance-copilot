-- -------------------------------------------------------
-- 4.2 Dynamic Table: Fraud Signals (5-min refresh)
-- -------------------------------------------------------
CREATE OR REPLACE DYNAMIC TABLE BANKING_COMPLIANCE_AI.ANALYTICS.FRAUD_SIGNALS
  TARGET_LAG = '5 minutes'
  WAREHOUSE = COMPUTE_WH
  REFRESH_MODE = AUTO
  COMMENT = 'Real-time fraud detection: velocity anomalies, impossible travel, device switching'
AS
WITH txn_velocity AS (
    SELECT t.ACCOUNT_ID, t.TRANSACTION_DATE,
        COUNT(*) OVER (PARTITION BY t.ACCOUNT_ID ORDER BY t.TRANSACTION_DATE RANGE BETWEEN INTERVAL '30 MINUTES' PRECEDING AND CURRENT ROW) AS txn_count_30min,
        COUNT(DISTINCT t.DEVICE_ID) OVER (PARTITION BY t.ACCOUNT_ID ORDER BY t.TRANSACTION_DATE RANGE BETWEEN INTERVAL '30 MINUTES' PRECEDING AND CURRENT ROW) AS distinct_devices_30min
    FROM BANKING_COMPLIANCE_AI.RAW_DATA.TRANSACTIONS t
),
geo_anomaly AS (
    SELECT t.TRANSACTION_ID, t.ACCOUNT_ID, t.AMOUNT, t.TRANSACTION_TYPE, t.CHANNEL,
        t.TRANSACTION_DATE, t.ORIGINATOR_COUNTRY, t.BENEFICIARY_COUNTRY,
        t.GEO_LATITUDE, t.GEO_LONGITUDE, t.DEVICE_ID, t.IP_ADDRESS, t.IS_CROSS_BORDER,
        LAG(t.GEO_LATITUDE) OVER (PARTITION BY t.ACCOUNT_ID ORDER BY t.TRANSACTION_DATE) AS prev_lat,
        LAG(t.GEO_LONGITUDE) OVER (PARTITION BY t.ACCOUNT_ID ORDER BY t.TRANSACTION_DATE) AS prev_lon,
        LAG(t.TRANSACTION_DATE) OVER (PARTITION BY t.ACCOUNT_ID ORDER BY t.TRANSACTION_DATE) AS prev_txn_date,
        CASE WHEN LAG(t.GEO_LATITUDE) OVER (PARTITION BY t.ACCOUNT_ID ORDER BY t.TRANSACTION_DATE) IS NOT NULL
            THEN 6371 * ACOS(LEAST(1, COS(RADIANS(t.GEO_LATITUDE)) * COS(RADIANS(LAG(t.GEO_LATITUDE) OVER (PARTITION BY t.ACCOUNT_ID ORDER BY t.TRANSACTION_DATE)))
                * COS(RADIANS(LAG(t.GEO_LONGITUDE) OVER (PARTITION BY t.ACCOUNT_ID ORDER BY t.TRANSACTION_DATE)) - RADIANS(t.GEO_LONGITUDE))
                + SIN(RADIANS(t.GEO_LATITUDE)) * SIN(RADIANS(LAG(t.GEO_LATITUDE) OVER (PARTITION BY t.ACCOUNT_ID ORDER BY t.TRANSACTION_DATE)))))
            ELSE NULL END AS distance_km,
        DATEDIFF(MINUTE, LAG(t.TRANSACTION_DATE) OVER (PARTITION BY t.ACCOUNT_ID ORDER BY t.TRANSACTION_DATE), t.TRANSACTION_DATE) AS minutes_since_prev
    FROM BANKING_COMPLIANCE_AI.RAW_DATA.TRANSACTIONS t
)
SELECT g.TRANSACTION_ID, g.ACCOUNT_ID, a.CUSTOMER_ID, c.FULL_NAME, c.RISK_RATING,
    g.AMOUNT, g.TRANSACTION_TYPE, g.CHANNEL, g.TRANSACTION_DATE,
    g.ORIGINATOR_COUNTRY, g.BENEFICIARY_COUNTRY, g.DEVICE_ID, g.IP_ADDRESS,
    ROUND(g.distance_km, 1) AS distance_from_prev_km, g.minutes_since_prev,
    CASE WHEN g.distance_km > 500 AND g.minutes_since_prev < 60 THEN 'IMPOSSIBLE_TRAVEL'
         WHEN v.txn_count_30min > 3 THEN 'VELOCITY_SPIKE'
         WHEN v.distinct_devices_30min > 2 THEN 'DEVICE_SWITCHING'
         WHEN g.distance_km > 200 AND g.minutes_since_prev < 120 THEN 'SUSPICIOUS_TRAVEL'
    END AS FRAUD_SIGNAL_TYPE,
    CASE WHEN g.distance_km > 500 AND g.minutes_since_prev < 60 THEN 'CRITICAL'
         WHEN v.txn_count_30min > 5 THEN 'CRITICAL'
         WHEN v.txn_count_30min > 3 OR v.distinct_devices_30min > 2 THEN 'HIGH'
         ELSE 'MEDIUM' END AS SEVERITY,
    v.txn_count_30min, v.distinct_devices_30min,
    CURRENT_TIMESTAMP() AS DETECTED_AT
FROM geo_anomaly g
JOIN BANKING_COMPLIANCE_AI.RAW_DATA.ACCOUNTS a ON g.ACCOUNT_ID = a.ACCOUNT_ID
JOIN BANKING_COMPLIANCE_AI.RAW_DATA.CUSTOMERS c ON a.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN txn_velocity v ON g.ACCOUNT_ID = v.ACCOUNT_ID AND g.TRANSACTION_DATE = v.TRANSACTION_DATE
WHERE (g.distance_km > 200 AND g.minutes_since_prev < 120) OR v.txn_count_30min > 3 OR v.distinct_devices_30min > 2;

-- -------------------------------------------------------
-- 4.3 Dynamic Table: AML Alerts (5-min refresh)
-- -------------------------------------------------------
CREATE OR REPLACE DYNAMIC TABLE BANKING_COMPLIANCE_AI.ANALYTICS.AML_ALERTS
  TARGET_LAG = '5 minutes'
  WAREHOUSE = COMPUTE_WH
  REFRESH_MODE = AUTO
  COMMENT = 'AML detection: structuring, shell company wires, layering/round-tripping'
AS
SELECT 'STRUCTURING' AS ALERT_TYPE, t.ACCOUNT_ID, a.CUSTOMER_ID, c.FULL_NAME, c.RISK_RATING, c.PEP_FLAG,
    COUNT(*) AS PATTERN_COUNT, SUM(t.AMOUNT) AS TOTAL_AMOUNT,
    MIN(t.TRANSACTION_DATE) AS FIRST_TXN_DATE, MAX(t.TRANSACTION_DATE) AS LAST_TXN_DATE,
    'Multiple cash deposits between INR 8.9L-10L - potential CTR evasion per PMLA Rules 2005' AS DESCRIPTION,
    CASE WHEN COUNT(*) >= 5 THEN 'CRITICAL' WHEN COUNT(*) >= 3 THEN 'HIGH' ELSE 'MEDIUM' END AS SEVERITY,
    'STR filing required per PMLA Section 12; report to FIU-IND' AS REGULATORY_ACTION
FROM BANKING_COMPLIANCE_AI.RAW_DATA.TRANSACTIONS t
JOIN BANKING_COMPLIANCE_AI.RAW_DATA.ACCOUNTS a ON t.ACCOUNT_ID = a.ACCOUNT_ID
JOIN BANKING_COMPLIANCE_AI.RAW_DATA.CUSTOMERS c ON a.CUSTOMER_ID = c.CUSTOMER_ID
WHERE t.TRANSACTION_TYPE = 'CASH_DEPOSIT' AND t.AMOUNT BETWEEN 890000 AND 999999
GROUP BY t.ACCOUNT_ID, a.CUSTOMER_ID, c.FULL_NAME, c.RISK_RATING, c.PEP_FLAG HAVING COUNT(*) >= 2
UNION ALL
SELECT 'HIGH_RISK_WIRE', t.ACCOUNT_ID, a.CUSTOMER_ID, c.FULL_NAME, c.RISK_RATING, c.PEP_FLAG,
    COUNT(*), SUM(t.AMOUNT), MIN(t.TRANSACTION_DATE), MAX(t.TRANSACTION_DATE),
    'Cross-border wire to high-risk/sanctioned counterparty',
    CASE WHEN MAX(CASE WHEN cp.SANCTIONS_LISTED THEN 1 ELSE 0 END) = 1 THEN 'CRITICAL'
         WHEN SUM(t.AMOUNT) > 10000000 THEN 'CRITICAL' ELSE 'HIGH' END,
    'Immediate STR + enhanced monitoring per RBI Master Direction on KYC'
FROM BANKING_COMPLIANCE_AI.RAW_DATA.TRANSACTIONS t
JOIN BANKING_COMPLIANCE_AI.RAW_DATA.ACCOUNTS a ON t.ACCOUNT_ID = a.ACCOUNT_ID
JOIN BANKING_COMPLIANCE_AI.RAW_DATA.CUSTOMERS c ON a.CUSTOMER_ID = c.CUSTOMER_ID
JOIN BANKING_COMPLIANCE_AI.RAW_DATA.COUNTERPARTIES cp ON t.COUNTERPARTY_ID = cp.COUNTERPARTY_ID
WHERE t.IS_CROSS_BORDER = TRUE AND (cp.RISK_JURISDICTION = TRUE OR cp.SANCTIONS_LISTED = TRUE OR cp.ENTITY_TYPE = 'SHELL_COMPANY')
GROUP BY t.ACCOUNT_ID, a.CUSTOMER_ID, c.FULL_NAME, c.RISK_RATING, c.PEP_FLAG
UNION ALL
SELECT 'LAYERING', outb.ACCOUNT_ID, a.CUSTOMER_ID, c.FULL_NAME, c.RISK_RATING, c.PEP_FLAG,
    COUNT(*), SUM(outb.AMOUNT), MIN(outb.TRANSACTION_DATE), MAX(inb.TRANSACTION_DATE),
    'Funds received and moved out within 3 days - potential layering',
    CASE WHEN SUM(outb.AMOUNT) > 20000000 THEN 'CRITICAL' WHEN COUNT(*) >= 3 THEN 'HIGH' ELSE 'MEDIUM' END,
    'STR filing + enhanced due diligence per FIU-IND Red Flag Indicators'
FROM BANKING_COMPLIANCE_AI.RAW_DATA.TRANSACTIONS outb
JOIN BANKING_COMPLIANCE_AI.RAW_DATA.TRANSACTIONS inb ON outb.ACCOUNT_ID = inb.ACCOUNT_ID
    AND inb.TRANSACTION_DATE < outb.TRANSACTION_DATE
    AND DATEDIFF(DAY, inb.TRANSACTION_DATE, outb.TRANSACTION_DATE) <= 3
    AND inb.AMOUNT BETWEEN outb.AMOUNT * 0.9 AND outb.AMOUNT * 1.1
    AND inb.IS_CROSS_BORDER = TRUE AND outb.IS_CROSS_BORDER = TRUE
JOIN BANKING_COMPLIANCE_AI.RAW_DATA.ACCOUNTS a ON outb.ACCOUNT_ID = a.ACCOUNT_ID
JOIN BANKING_COMPLIANCE_AI.RAW_DATA.CUSTOMERS c ON a.CUSTOMER_ID = c.CUSTOMER_ID
GROUP BY outb.ACCOUNT_ID, a.CUSTOMER_ID, c.FULL_NAME, c.RISK_RATING, c.PEP_FLAG;

-- -------------------------------------------------------
-- 4.4 Dynamic Table: Basel III Metrics (30-min refresh)
-- -------------------------------------------------------
CREATE OR REPLACE DYNAMIC TABLE BANKING_COMPLIANCE_AI.ANALYTICS.BASEL_METRICS
  TARGET_LAG = '30 minutes'
  WAREHOUSE = COMPUTE_WH
  REFRESH_MODE = AUTO
  COMMENT = 'Basel III LCR and NSFR computation'
AS
WITH hqla_calc AS (
    SELECT HQLA_LEVEL,
        SUM(CASE WHEN IS_ENCUMBERED = FALSE THEN MARKET_VALUE ELSE 0 END) AS GROSS_MARKET_VALUE,
        SUM(CASE WHEN IS_ENCUMBERED = FALSE THEN MARKET_VALUE * (1 - HAIRCUT_PCT / 100) ELSE 0 END) AS ADJUSTED_HQLA,
        COUNT(*) AS ASSET_COUNT, MAX(AS_OF_DATE) AS AS_OF_DATE
    FROM BANKING_COMPLIANCE_AI.RAW_DATA.HQLA_PORTFOLIO GROUP BY HQLA_LEVEL
),
total_hqla AS (SELECT SUM(ADJUSTED_HQLA) AS TOTAL_ADJUSTED_HQLA FROM hqla_calc),
outflow_calc AS (
    SELECT SUM(AMOUNT * RUNOFF_RATE_PCT / 100) AS TOTAL_STRESSED_OUTFLOW
    FROM BANKING_COMPLIANCE_AI.RAW_DATA.CASH_FLOWS
    WHERE FLOW_TYPE = 'OUTFLOW' AND MATURITY_BUCKET IN ('OVERNIGHT','2_7_DAYS','8_30_DAYS')
),
inflow_calc AS (
    SELECT SUM(AMOUNT * RUNOFF_RATE_PCT / 100) AS TOTAL_STRESSED_INFLOW
    FROM BANKING_COMPLIANCE_AI.RAW_DATA.CASH_FLOWS
    WHERE FLOW_TYPE = 'INFLOW' AND MATURITY_BUCKET IN ('OVERNIGHT','2_7_DAYS','8_30_DAYS')
),
lcr_calc AS (
    SELECT th.TOTAL_ADJUSTED_HQLA, oc.TOTAL_STRESSED_OUTFLOW, ic.TOTAL_STRESSED_INFLOW,
        LEAST(ic.TOTAL_STRESSED_INFLOW, oc.TOTAL_STRESSED_OUTFLOW * 0.75) AS CAPPED_INFLOW,
        oc.TOTAL_STRESSED_OUTFLOW - LEAST(ic.TOTAL_STRESSED_INFLOW, oc.TOTAL_STRESSED_OUTFLOW * 0.75) AS NET_CASH_OUTFLOW,
        DIV0NULL(th.TOTAL_ADJUSTED_HQLA, oc.TOTAL_STRESSED_OUTFLOW - LEAST(ic.TOTAL_STRESSED_INFLOW, oc.TOTAL_STRESSED_OUTFLOW * 0.75)) * 100 AS LCR_PERCENT
    FROM total_hqla th CROSS JOIN outflow_calc oc CROSS JOIN inflow_calc ic
)
SELECT 'LCR_SUMMARY' AS METRIC_TYPE, 'Liquidity Coverage Ratio' AS METRIC_NAME,
    lc.LCR_PERCENT AS METRIC_VALUE, 'PERCENT' AS METRIC_UNIT,
    CASE WHEN lc.LCR_PERCENT >= 100 THEN 'COMPLIANT' ELSE 'NON_COMPLIANT' END AS STATUS,
    100 AS REGULATORY_MINIMUM, lc.TOTAL_ADJUSTED_HQLA, lc.TOTAL_STRESSED_OUTFLOW,
    lc.TOTAL_STRESSED_INFLOW, lc.CAPPED_INFLOW, lc.NET_CASH_OUTFLOW,
    'RBI Basel III Liquidity Standards, April 2019 / BCBS 238' AS REGULATORY_REFERENCE
FROM lcr_calc lc
UNION ALL
SELECT 'HQLA_' || h.HQLA_LEVEL, 'HQLA ' || h.HQLA_LEVEL || ' (adjusted)',
    h.ADJUSTED_HQLA, 'INR',
    CASE WHEN h.HQLA_LEVEL = 'LEVEL_2A' AND DIV0NULL(h.ADJUSTED_HQLA, th.TOTAL_ADJUSTED_HQLA) > 0.40 THEN 'CAP_BREACHED'
         WHEN h.HQLA_LEVEL = 'LEVEL_2B' AND DIV0NULL(h.ADJUSTED_HQLA, th.TOTAL_ADJUSTED_HQLA) > 0.15 THEN 'CAP_BREACHED'
         ELSE 'WITHIN_LIMITS' END,
    CASE h.HQLA_LEVEL WHEN 'LEVEL_2A' THEN 40 WHEN 'LEVEL_2B' THEN 15 ELSE NULL END,
    h.GROSS_MARKET_VALUE, NULL, NULL, NULL, NULL, 'Basel III LCR Paragraphs 50-54'
FROM hqla_calc h CROSS JOIN total_hqla th;

-- -------------------------------------------------------
-- 4.5 Cortex Search Service (regulatory documents)
-- -------------------------------------------------------
CREATE OR REPLACE CORTEX SEARCH SERVICE BANKING_COMPLIANCE_AI.REFERENCE_DATA.REGULATORY_SEARCH
  ON CONTENT
  ATTRIBUTES REGULATION, TITLE, SECTION, ISSUER, JURISDICTION
  WAREHOUSE = COMPUTE_WH
  TARGET_LAG = '1 hour'
  COMMENT = 'Search service for RBI circulars, PMLA rules, Basel guidelines, FATF recommendations'
AS (
  SELECT DOC_ID, REGULATION, TITLE, SECTION, CONTENT, ISSUER, JURISDICTION
  FROM BANKING_COMPLIANCE_AI.REFERENCE_DATA.REGULATORY_DOCUMENTS
);

-- -------------------------------------------------------
-- 4.6 Scheduled Task: Compliance Report Generation
-- -------------------------------------------------------
CREATE OR REPLACE TASK BANKING_COMPLIANCE_AI.ANALYTICS.GENERATE_COMPLIANCE_REPORT
  WAREHOUSE = COMPUTE_WH
  SCHEDULE = 'USING CRON 0 */6 * * * Asia/Kolkata'
  COMMENT = 'Consolidates fraud signals, AML alerts, and Basel metrics into audit-ready compliance reports'
AS
    INSERT INTO BANKING_COMPLIANCE_AI.ANALYTICS.COMPLIANCE_REPORTS
    (REPORT_ID, REPORT_DATE, REPORT_TYPE, ALERT_TYPE, SEVERITY, ACCOUNT_ID, CUSTOMER_ID, CUSTOMER_NAME, RISK_RATING, DESCRIPTION, TOTAL_AMOUNT, PATTERN_COUNT, REGULATORY_ACTION, REGULATORY_REFERENCE, STATUS)
    SELECT
        'RPT-A-' || TO_VARCHAR(CURRENT_TIMESTAMP(), 'YYYYMMDDHH24MISS') || '-' || ABS(HASH(a.ACCOUNT_ID || a.ALERT_TYPE)) % 100000,
        CURRENT_TIMESTAMP(), 'AML_ALERT', a.ALERT_TYPE, a.SEVERITY, a.ACCOUNT_ID, a.CUSTOMER_ID,
        a.FULL_NAME, a.RISK_RATING, a.DESCRIPTION, a.TOTAL_AMOUNT, a.PATTERN_COUNT, a.REGULATORY_ACTION,
        CASE a.ALERT_TYPE WHEN 'STRUCTURING' THEN 'PMLA Rules 2005, Section 12'
             WHEN 'HIGH_RISK_WIRE' THEN 'RBI Master Direction on KYC, FATF Recommendations'
             WHEN 'LAYERING' THEN 'FIU-IND Red Flag Indicators' END,
        'OPEN'
    FROM BANKING_COMPLIANCE_AI.ANALYTICS.AML_ALERTS a
    WHERE NOT EXISTS (
        SELECT 1 FROM BANKING_COMPLIANCE_AI.ANALYTICS.COMPLIANCE_REPORTS cr
        WHERE cr.ACCOUNT_ID = a.ACCOUNT_ID AND cr.ALERT_TYPE = a.ALERT_TYPE
        AND cr.REPORT_TYPE = 'AML_ALERT' AND cr.CREATED_AT > DATEADD(HOUR, -6, CURRENT_TIMESTAMP())
    );

ALTER TASK BANKING_COMPLIANCE_AI.ANALYTICS.GENERATE_COMPLIANCE_REPORT RESUME;
