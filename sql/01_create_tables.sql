-- ============================================================
-- Banking Compliance AI — Step 1: Database, Schemas, and Tables
-- Run this first to create the data foundation.
-- ============================================================

CREATE DATABASE IF NOT EXISTS BANKING_COMPLIANCE_AI
  COMMENT = 'End-to-end banking compliance solution: fraud detection, AML, Basel metrics';

CREATE SCHEMA IF NOT EXISTS BANKING_COMPLIANCE_AI.RAW_DATA
  COMMENT = 'Synthetic base tables: customers, accounts, transactions, counterparties';

CREATE SCHEMA IF NOT EXISTS BANKING_COMPLIANCE_AI.REFERENCE_DATA
  COMMENT = 'Regulatory thresholds, risk parameters, AML rules';

CREATE SCHEMA IF NOT EXISTS BANKING_COMPLIANCE_AI.ANALYTICS
  COMMENT = 'Derived views, metrics, and detection results';

-- Customers
CREATE OR REPLACE TABLE BANKING_COMPLIANCE_AI.RAW_DATA.CUSTOMERS (
    CUSTOMER_ID         VARCHAR(20)   NOT NULL PRIMARY KEY,
    FULL_NAME           VARCHAR(200)  NOT NULL,
    DATE_OF_BIRTH       DATE,
    NATIONALITY         VARCHAR(50),
    COUNTRY_OF_RESIDENCE VARCHAR(50)  NOT NULL,
    CITY                VARCHAR(100),
    CUSTOMER_TYPE       VARCHAR(20)   NOT NULL,
    KYC_STATUS          VARCHAR(20)   NOT NULL,
    KYC_VERIFIED_DATE   TIMESTAMP_NTZ,
    RISK_RATING         VARCHAR(10)   NOT NULL,
    PEP_FLAG            BOOLEAN       DEFAULT FALSE,
    SANCTIONS_FLAG      BOOLEAN       DEFAULT FALSE,
    INDUSTRY_CODE       VARCHAR(20),
    ANNUAL_INCOME       NUMBER(18,2),
    SOURCE_OF_FUNDS     VARCHAR(100),
    ONBOARDING_DATE     DATE          NOT NULL,
    LAST_REVIEW_DATE    DATE,
    CREATED_AT          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Accounts
CREATE OR REPLACE TABLE BANKING_COMPLIANCE_AI.RAW_DATA.ACCOUNTS (
    ACCOUNT_ID          VARCHAR(20)   NOT NULL PRIMARY KEY,
    CUSTOMER_ID         VARCHAR(20)   NOT NULL REFERENCES BANKING_COMPLIANCE_AI.RAW_DATA.CUSTOMERS(CUSTOMER_ID),
    ACCOUNT_TYPE        VARCHAR(30)   NOT NULL,
    CURRENCY            VARCHAR(3)    NOT NULL DEFAULT 'INR',
    OPENING_DATE        DATE          NOT NULL,
    STATUS              VARCHAR(15)   NOT NULL,
    CURRENT_BALANCE     NUMBER(18,2)  NOT NULL DEFAULT 0,
    CREDIT_LIMIT        NUMBER(18,2),
    BRANCH_CODE         VARCHAR(10),
    IS_JOINT_ACCOUNT    BOOLEAN       DEFAULT FALSE,
    CREATED_AT          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Counterparties
CREATE OR REPLACE TABLE BANKING_COMPLIANCE_AI.RAW_DATA.COUNTERPARTIES (
    COUNTERPARTY_ID     VARCHAR(20)   NOT NULL PRIMARY KEY,
    NAME                VARCHAR(200)  NOT NULL,
    ENTITY_TYPE         VARCHAR(20)   NOT NULL,
    COUNTRY             VARCHAR(50)   NOT NULL,
    RISK_JURISDICTION   BOOLEAN       DEFAULT FALSE,
    SWIFT_CODE          VARCHAR(11),
    IS_CORRESPONDENT    BOOLEAN       DEFAULT FALSE,
    SANCTIONS_LISTED    BOOLEAN       DEFAULT FALSE,
    CREATED_AT          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Transactions
CREATE OR REPLACE TABLE BANKING_COMPLIANCE_AI.RAW_DATA.TRANSACTIONS (
    TRANSACTION_ID      VARCHAR(30)   NOT NULL PRIMARY KEY,
    ACCOUNT_ID          VARCHAR(20)   NOT NULL REFERENCES BANKING_COMPLIANCE_AI.RAW_DATA.ACCOUNTS(ACCOUNT_ID),
    COUNTERPARTY_ID     VARCHAR(20)   REFERENCES BANKING_COMPLIANCE_AI.RAW_DATA.COUNTERPARTIES(COUNTERPARTY_ID),
    TRANSACTION_TYPE    VARCHAR(30)   NOT NULL,
    CHANNEL             VARCHAR(20)   NOT NULL,
    AMOUNT              NUMBER(18,2)  NOT NULL,
    CURRENCY            VARCHAR(3)    NOT NULL DEFAULT 'INR',
    TRANSACTION_DATE    TIMESTAMP_NTZ NOT NULL,
    VALUE_DATE          DATE,
    ORIGINATOR_NAME     VARCHAR(200),
    BENEFICIARY_NAME    VARCHAR(200),
    ORIGINATOR_COUNTRY  VARCHAR(50),
    BENEFICIARY_COUNTRY VARCHAR(50),
    PURPOSE_CODE        VARCHAR(50),
    REFERENCE_NOTE      VARCHAR(500),
    IS_CROSS_BORDER     BOOLEAN       DEFAULT FALSE,
    IP_ADDRESS          VARCHAR(45),
    DEVICE_ID           VARCHAR(100),
    GEO_LATITUDE        FLOAT,
    GEO_LONGITUDE       FLOAT,
    STATUS              VARCHAR(15)   NOT NULL DEFAULT 'COMPLETED',
    CREATED_AT          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- HQLA Portfolio (High-Quality Liquid Assets for Basel III)
CREATE OR REPLACE TABLE BANKING_COMPLIANCE_AI.RAW_DATA.HQLA_PORTFOLIO (
    ASSET_ID            VARCHAR(20)   NOT NULL PRIMARY KEY,
    ASSET_TYPE          VARCHAR(30)   NOT NULL,
    HQLA_LEVEL          VARCHAR(10)   NOT NULL,
    ISSUER              VARCHAR(200),
    CURRENCY            VARCHAR(3)    NOT NULL DEFAULT 'INR',
    FACE_VALUE          NUMBER(18,2)  NOT NULL,
    MARKET_VALUE        NUMBER(18,2)  NOT NULL,
    HAIRCUT_PCT         NUMBER(5,2)   NOT NULL DEFAULT 0,
    MATURITY_DATE       DATE,
    IS_ENCUMBERED       BOOLEAN       DEFAULT FALSE,
    AS_OF_DATE          DATE          NOT NULL,
    CREATED_AT          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Cash Flows (for LCR/NSFR computation)
CREATE OR REPLACE TABLE BANKING_COMPLIANCE_AI.RAW_DATA.CASH_FLOWS (
    FLOW_ID             VARCHAR(20)   NOT NULL PRIMARY KEY,
    FLOW_TYPE           VARCHAR(15)   NOT NULL,
    CATEGORY            VARCHAR(50)   NOT NULL,
    COUNTERPARTY_TYPE   VARCHAR(30),
    AMOUNT              NUMBER(18,2)  NOT NULL,
    CURRENCY            VARCHAR(3)    NOT NULL DEFAULT 'INR',
    RUNOFF_RATE_PCT     NUMBER(5,2)   NOT NULL,
    MATURITY_BUCKET     VARCHAR(20)   NOT NULL,
    AS_OF_DATE          DATE          NOT NULL,
    CREATED_AT          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Regulatory Thresholds
CREATE OR REPLACE TABLE BANKING_COMPLIANCE_AI.REFERENCE_DATA.REGULATORY_THRESHOLDS (
    RULE_ID             VARCHAR(30)   NOT NULL PRIMARY KEY,
    REGULATION          VARCHAR(20)   NOT NULL,
    RULE_NAME           VARCHAR(200)  NOT NULL,
    DESCRIPTION         VARCHAR(1000),
    THRESHOLD_VALUE     NUMBER(18,2),
    THRESHOLD_UNIT      VARCHAR(30),
    JURISDICTION        VARCHAR(50)   DEFAULT 'INDIA',
    EFFECTIVE_FROM      DATE          NOT NULL,
    EFFECTIVE_TO        DATE,
    SOURCE_REFERENCE    VARCHAR(500),
    CREATED_AT          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Regulatory Documents (for Cortex Search)
CREATE OR REPLACE TABLE BANKING_COMPLIANCE_AI.REFERENCE_DATA.REGULATORY_DOCUMENTS (
    DOC_ID          VARCHAR(30)    NOT NULL PRIMARY KEY,
    REGULATION      VARCHAR(30)    NOT NULL,
    TITLE           VARCHAR(500)   NOT NULL,
    SECTION         VARCHAR(200),
    CONTENT         VARCHAR(16000) NOT NULL,
    ISSUER          VARCHAR(100)   NOT NULL,
    EFFECTIVE_DATE  DATE,
    JURISDICTION    VARCHAR(50)    DEFAULT 'INDIA',
    DOC_URL         VARCHAR(500),
    CREATED_AT      TIMESTAMP_NTZ  DEFAULT CURRENT_TIMESTAMP()
);

-- Compliance Reports (output table)
CREATE OR REPLACE TABLE BANKING_COMPLIANCE_AI.ANALYTICS.COMPLIANCE_REPORTS (
    REPORT_ID           VARCHAR(50)    NOT NULL,
    REPORT_DATE         TIMESTAMP_NTZ  NOT NULL,
    REPORT_TYPE         VARCHAR(30)    NOT NULL,
    ALERT_TYPE          VARCHAR(30),
    SEVERITY            VARCHAR(10),
    ACCOUNT_ID          VARCHAR(20),
    CUSTOMER_ID         VARCHAR(20),
    CUSTOMER_NAME       VARCHAR(200),
    RISK_RATING         VARCHAR(10),
    DESCRIPTION         VARCHAR(2000),
    TOTAL_AMOUNT        NUMBER(18,2),
    PATTERN_COUNT       NUMBER,
    REGULATORY_ACTION   VARCHAR(500),
    REGULATORY_REFERENCE VARCHAR(500),
    STATUS              VARCHAR(20)    DEFAULT 'OPEN',
    ASSIGNED_TO         VARCHAR(100),
    CREATED_AT          TIMESTAMP_NTZ  DEFAULT CURRENT_TIMESTAMP()
);
